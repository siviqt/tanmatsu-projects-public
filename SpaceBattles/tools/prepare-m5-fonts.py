#!/usr/bin/env python3
"""Offline PAX 2-bit coverage bitmap conversion. Requires Pillow with FreeType.
Sources/licenses are vendored; firmware builds use the generated C directly.
"""
from pathlib import Path
from hashlib import sha256
from PIL import Image, ImageDraw, ImageFont, features
import PIL
import argparse
root = Path(__file__).resolve().parents[1]
assets = root / 'components/spacebattles/assets/fonts'
out = root / 'components/spacebattles/render/font_assets.c'
expected = {
    'Oxanium.ttf': '2ce01d946e1e1ffc8d7eecfffbda8623bedd63eaf811a20488c4b69af45babb0',
    'SpaceMono-Regular.ttf': '95837e182baeeada83368f7748db28357f0a1b75c6b84ff7065b5edf933c8e18',
}
for filename, digest in expected.items():
    assert sha256((assets/filename).read_bytes()).hexdigest() == digest, f'Font source changed: {filename}'

profiles = (16, 20, 26)
# caption, body, button, heading, timer, coordinate, telemetry
roles = (('ox',500,-2), ('ox',500,0), ('ox',600,0), ('ox',700,8),
         ('mono',400,4), ('mono',400,0), ('mono',400,-2))
lines = ['// Generated by tools/prepare-m5-fonts.py; font data licensed under bundled OFL.',
         '#include "render/typography.h"']
keys = sorted({(family, weight, base+delta) for base in profiles for family,weight,delta in roles})
for family, weight, size in keys:
    name = f'{family}_{weight}_{size}'
    path = assets / ('Oxanium.ttf' if family == 'ox' else 'SpaceMono-Regular.ttf')
    font = ImageFont.truetype(str(path), size, layout_engine=ImageFont.Layout.BASIC)
    if family == 'ox': font.set_variation_by_axes([weight])
    ascent, descent = font.getmetrics()
    data, dims = [], []
    for code in range(32,127):
        char = chr(code)
        left, top, right, bottom = font.getbbox(char, anchor='ls')
        w,h = right-left,bottom-top
        index = len(data)
        if w and h:
            im = Image.new('L',(w,h))
            ImageDraw.Draw(im).text((-left,-top),char,font=font,anchor='ls',fill=255)
            pixels = list(im.tobytes())
            for y in range(h):
                for x in range(0,w,4):
                    data.append(sum(((pixels[y*w+i]*3+127)//255) << (2*(i-x))
                                    for i in range(x,min(x+4,w))))
        dims.append(f'{{.draw_x={left},.draw_y={top+ascent},.draw_w={w},.draw_h={h},.index={index},.measured_width={round(font.getlength(char))}}},')
    lines.append(f'static const uint8_t {name}_pixels[] = {{')
    lines.extend(','.join(map(str,data[i:i+32]))+',' for i in range(0,len(data),32))
    lines += ['};',f'static const pax_bmpv_t {name}_dims[] = {{',*dims,'};',
        f'static const pax_font_range_t {name}_range = {{.type=PAX_FONT_TYPE_BITMAP_VAR,.start=32,.end=126,.bitmap_var={{.glyphs={name}_pixels,.dims={name}_dims,.height={ascent+descent},.bpp=2}}}};',
        f'static const pax_font_t {name} = {{.name="SB {family} {weight} {size}",.n_ranges=1,.ranges=&{name}_range,.default_size={size},.recommend_aa=true}};']
lines.append('const sb_font_t sb_font_assets[SB_FONT_PROFILE_COUNT][SB_FONT_ROLE_COUNT] = {')
for base in profiles:
    lines.append('{'+','.join(f'{{&{family}_{weight}_{base+delta},{base+delta}}}' for family,weight,delta in roles)+'},')
lines.append('};\n')
content='\n'.join(lines)
parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true'); args=parser.parse_args()
if args.check:
    assert out.read_text()==content, 'Generated font assets differ; regenerate with recorded converter versions'
else: out.write_text(content)
print(f'Pillow {PIL.__version__}; FreeType {features.version("freetype2")}; {len(keys)} font strikes')
for path in sorted(assets.glob('*.ttf')): print(path.name,sha256(path.read_bytes()).hexdigest())
